package sidecarzero

import (
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestArenaAccessLint is the lint of testing §2.3 for Go: arena memory is reachable only
// through the generated accessors. Go's atomics cannot be too weak, but a plain read or
// write of arena memory can be written, and it is a race with another process that no tool
// in this process can see. The rules, over every non-test file of the module:
//
//  1. unsafe is imported only by internal/abi's seg*.go (Seg and its primitives) and by
//     internal/sys (clock_gettime and the stack hint): nothing else can form a pointer into
//     a mapping.
//  2. syscall.Mmap and syscall.Munmap are called only in internal/abi: no other code holds
//     a []byte over arena memory.
//  3. Inside internal/abi, Seg's unexported primitives (ld64, st64, ld32, st32, cas32,
//     cas64, add32, add64) are called only by the generated abi.go and by seg*.go itself.
//  4. The worker's and the supervisor's views (abi.Worker, abi.Supervisor) are used only by
//     the in-process double (inprocess.go, internal/shm/local.go): the client writes only
//     the fields the ABI file says a client writes.
//  5. abi.go is the generator's output (its header says so).
func TestArenaAccessLint(t *testing.T) {
	primitives := map[string]bool{"ld64": true, "st64": true, "ld32": true, "st32": true, "cas32": true, "cas64": true, "add32": true, "add64": true}
	n := 0
	err := filepath.WalkDir(".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		n++
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		f, err := parser.ParseFile(token.NewFileSet(), path, src, parser.ImportsOnly|parser.ParseComments)
		if err != nil {
			return err
		}
		dir, base := filepath.Dir(path), filepath.Base(path)
		inAbi := dir == filepath.Join("internal", "abi")
		for _, im := range f.Imports {
			if im.Path.Value == `"unsafe"` && !(inAbi && strings.HasPrefix(base, "seg")) && dir != filepath.Join("internal", "sys") {
				t.Errorf("%s imports unsafe (rule 1)", path)
			}
		}
		full, err := parser.ParseFile(token.NewFileSet(), path, src, 0)
		if err != nil {
			return err
		}
		ast.Inspect(full, func(nd ast.Node) bool {
			call, ok := nd.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			name := sel.Sel.Name
			if x, ok := sel.X.(*ast.Ident); ok {
				if x.Name == "syscall" && (name == "Mmap" || name == "Munmap") && !inAbi {
					t.Errorf("%s calls syscall.%s (rule 2)", path, name)
				}
				if x.Name == "abi" && (name == "Worker" || name == "Supervisor") && path != "inprocess.go" && path != filepath.Join("internal", "shm", "local.go") {
					t.Errorf("%s uses abi.%s, a view the client must not use (rule 4)", path, name)
				}
			}
			if primitives[name] && inAbi && base != "abi.go" && !strings.HasPrefix(base, "seg") {
				t.Errorf("%s calls the primitive %s (rule 3)", path, name)
			}
			if primitives[name] && !inAbi {
				t.Errorf("%s calls %s outside internal/abi (rule 3)", path, name)
			}
			return true
		})
		if inAbi && base == "abi.go" && !strings.HasPrefix(string(src), "// Code generated by scz-abi-gen") {
			t.Errorf("%s is not the generator's output (rule 5)", path)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if n < 10 {
		t.Fatalf("only %d files seen", n)
	}
}
