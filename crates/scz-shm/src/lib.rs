//! scz-shm: the SidecarZero arena, shared by the supervisor, the workers, and the Rust SDK.
//!
//! | Module | What it holds | Design |
//! |---|---|---|
//! | [`abi`] | Constants and field accessors, generated from `abi/scz_abi.toml` | shm-abi §8 |
//! | [`word`] | Packing of the slot word and the gate word | shm-abi §5.2, §3 |
//! | [`ring`] | The MPSC descriptor ring: enqueue, dequeue, park, repair | shm-abi §4, signaling §3.1 |
//! | [`slot`] | The slot state machine, client, worker, and sweep sides | shm-abi §5–6, signaling §3.2 |
//! | [`wait`] | Futex waits and wakes, and the monotonic clock | signaling §5 |
//! | [`layout`] | Placing, writing, and reading back the segments' layout | shm-abi §2–3 |
//! | [`seg`] | Bounds-checked atomic views of a mapped segment | shm-abi §1 |
//! | [`arena`] | memfds, seals, and mappings (Linux) | shm-abi §2 |
//! | [`handshake`] | The session socket and its three messages (Linux) | supervisor §4 |
//! | [`deathlock`] | Robust mutexes that report a consume thread's death (Linux) | supervisor §5.2 |
//! | [`snapshot`] | Publishing an arena to request threads, and retiring it safely | sdk-contract §6 |
//! | [`standby`] | A warm worker waiting to be activated | supervisor §5.3 |
//! | [`view`] | What a codec may do with slot memory | sdk-rust §3.2 |
//! | [`registry`] | The model's columns and Arrow frame templates; the schema fingerprint | arrow-data-plane §4, §9 |
//! | [`arrowfb`] | A bounds-checked reader of the Arrow Schema and RecordBatch messages | arrow-data-plane §4, §10 |
//! | [`model`] | The model block and the registry under the model seqlock | shm-abi §3 |
//!
//! The protocol modules (`ring`, `slot`, `word`) are written against small traits, so the same
//! code runs over a mapped segment and, built with `--cfg loom`, inside loom's model checker
//! (`tests/loom.rs`). Everything that maps memory or makes system calls is left out of loom
//! builds.

