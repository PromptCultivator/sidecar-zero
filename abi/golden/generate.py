#!/usr/bin/env python3
"""Write abi/golden/arena.txt: the arena that [golden] in abi/scz_abi.toml describes, laid
out by the [layout] rule, as every implementation must reproduce it byte for byte.

    python3 abi/golden/generate.py           write the file
    python3 abi/golden/generate.py --check   exit 1 if it is missing or differs

This reads only the ABI file and shares no code with any implementation (testing §2.3): a
mistake in the Rust layout code cannot also be made here and go unnoticed. The output lists
every non-zero 64-bit little-endian word of both segments; every other word is zero.
Needs Python 3.11 or later (tomllib), and the xxhash package for the schema fingerprints,
which it also writes (abi/golden/fingerprints.txt).
"""
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "abi/golden/arena.txt"

spec = tomllib.loads((ROOT / "abi/scz_abi.toml").read_text())
C, D, G, R, E = spec["constants"], spec["defaults"], spec["golden"], spec["regions"], spec["enums"]
PAGE = spec["layout"]["page"]


def up(v, a):
    return (v + a - 1) // a * a


def pow2(v):
    p = 1
    while p < v:
        p *= 2
    return p


def width(ty):
    return {"u8": 1, "u16": 2, "u32": 4, "u64": 8}[ty]


def put(buf, region, base, name, value):
    f = next(f for f in R[region]["fields"] if f["name"] == name)
    w, off = width(f["ty"]), base + f["off"]
    buf[off:off + w] = value.to_bytes(w, "little")


def array(region, name, i):
    a = next(a for a in R[region]["arrays"] if a["name"] == name)
    assert i < a["count"]
    return a["off"] + i * a["stride"]


def crc32c(data):
    crc = 0xFFFFFFFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ (0x82F63B78 if crc & 1 else 0)
    return crc ^ 0xFFFFFFFF


assert crc32c(b"123456789") == 0xE3069283

# ── the [layout] rule ──
end = C["STATUS_PAGE_LEN"]
staging_off = end
end += C["BEAT_SLOTS"] * G["staging_len"]
rings = []
for r in G["rings"]:
    off = up(end, PAGE)
    rings.append((off, r["capacity"]))
    end = off + C["RING_HEADER_LEN"] + r["capacity"] * C["CELL_LEN"]
slabs = []
for c in G["slab_classes"]:
    table = up(end, PAGE)
    end = table + c["slot_count"] * C["SLOT_RECORD_LEN"]
    data_off = up(end, PAGE)
    end = data_off + c["slot_count"] * c["slot_size"]
    slabs.append((table, data_off, c))
data_len = pow2(end)
ctl_len = C["CTL_HEADER_LEN"] + C["CTL_REGISTRY_LEN"]

# ── control segment ──
ctl = bytearray(ctl_len)
h = "control_header"
for name, v in [
    ("magic", C["CTL_MAGIC"]), ("abi_major", spec["abi"]["major"]), ("abi_minor", spec["abi"]["minor"]),
    ("header_len", C["CTL_HEADER_LEN"]), ("data_len", data_len), ("arena_id", G["arena_id"]),
    ("ctl_len", ctl_len), ("page_size", PAGE), ("ring_count", len(rings)), ("slab_class_count", len(slabs)),
    ("feature_flags", 0), ("created_mono_ns", G["created_mono_ns"]),
] + [(k, D[k]) for k in ("hb_interval_ns", "hb_stale_ns", "spin_ns", "default_deadline_ns", "max_deadline_ns")]:
    put(ctl, h, 0, name, v)
for i, (off, cap) in enumerate(rings):
    b = array(h, "ring_dir", i)
    for name, v in [("ring_off", off), ("capacity", cap), ("kind", E["ring_kind"]["MPSC"]), ("cell_stride", C["CELL_LEN"])]:
        put(ctl, "ring_dir_entry", b, name, v)
for i, (table, data_off, c) in enumerate(slabs):
    b = array(h, "slab_dir", i)
    for name, v in [("table_off", table), ("data_off", data_off), ("slot_size", c["slot_size"]), ("slot_count", c["slot_count"]),
                    ("req_cap", c["req_cap"]), ("resp_cap", c["resp_cap"]), ("record_stride", C["SLOT_RECORD_LEN"])]:
        put(ctl, "slab_dir_entry", b, name, v)
b = array(h, "data_map", 0)
for name, v in [("status_off", 0), ("staging_off", staging_off), ("staging_len", G["staging_len"])]:
    put(ctl, "data_map", b, name, v)
put(ctl, h, 0, "layout_crc32c", crc32c(b"".join(bytes(ctl[a:z]) for a, z in R[h]["crc_ranges"])))

# ── data segment ──
data = bytearray(data_len)
put(data, "status_page", 0, "magic", C["DATA_MAGIC"])
put(data, "status_page", 0, "arena_id", G["arena_id"])
for i, (off, cap) in enumerate(rings):
    put(data, "ring_header", off, "ring_id", i)
    for k in range(cap):
        put(data, "cell", off + R["ring_header"]["cells_off"] + k * C["CELL_LEN"], "seq", k)


def words(name, buf):
    for off in range(0, len(buf), 8):
        w = int.from_bytes(buf[off:off + 8], "little")
        if w:
            yield f"{name} {off:#08x} {w:#018x}"


text = "\n".join([
    f"# @generated by abi/golden/generate.py from abi/scz_abi.toml (ABI {spec['abi']['major']}.{spec['abi']['minor']}). Do not edit.",
    "# The [golden] arena: every non-zero 64-bit little-endian word as `segment offset value`.",
    f"segments control {ctl_len:#x} data {data_len:#x}",
    *words("control", ctl),
    *words("data", data),
]) + "\n"

# ── Schema fingerprints (arrow-data-plane §9) ─────────────────────────────────────────────
# xxHash3-64, seed 0, over "SCZSCHEMA" 0x01, then for the request and the response columns:
# column_count u16, and per column name_len u16, name, elem_type u8, list_size u32, nullable u8.
# A schema is written `name:TYPE[list_size]`, `?` after the type for nullable, `,` between
# columns, `-` for no columns.
FP_OUT = ROOT / "abi/golden/fingerprints.txt"
FP_SCHEMAS = [
    ("features:F32[256]", "score:F32[1]"),
    ("features:F32[128]", "score:F32[1]"),
    ("features:F32[256]", "score:F32[2]"),
    ("feature:F32[256]", "score:F32[1]"),
    ("a:I64[1],b:F64?[1],c:FIXED_BINARY[16]", "emb:F32[8],p:F16[1]"),
    ("ids:U32[4],w:U8[1]", "-"),
    ("-", "-"),
    ("caf\u00e9:I8[3]", "r\u00e9sum\u00e9:U64[1]"),
]


def fp_columns(text):
    if text == "-":
        return []
    cols = []
    for c in text.split(","):
        name, rest = c.split(":")
        ty, size = rest.rstrip("]").split("[")
        nullable = ty.endswith("?")
        cols.append((name.encode("utf-8"), E["elem_type"][ty.rstrip("?")], int(size), nullable))
    return cols


def fingerprint(req, resp):
    import struct
    import xxhash

    b = bytearray(b"SCZSCHEMA\x01")
    for cols in (fp_columns(req), fp_columns(resp)):
        b += struct.pack("<H", len(cols))
        for name, elem, size, nullable in cols:
            b += struct.pack("<H", len(name)) + name + struct.pack("<BIB", elem, size, int(nullable))
    return xxhash.xxh3_64_intdigest(bytes(b), seed=0)


fp_text = "\n".join([
    "# @generated by abi/golden/generate.py from abi/scz_abi.toml. Do not edit.",
    "# Schema fingerprints: `fingerprint request response`; see generate.py for the notation.",
    *(f"{fingerprint(q, r):#018x} {q} {r}" for q, r in FP_SCHEMAS),
]) + "\n"

if "--check" in sys.argv:
    for path, body in ((OUT, text), (FP_OUT, fp_text)):
        if not path.exists() or path.read_text() != body:
            sys.exit(f"{path.relative_to(ROOT)} is out of date: run abi/golden/generate.py")
else:
    OUT.write_text(text)
    FP_OUT.write_text(fp_text)
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10)) - 3} words; {FP_OUT.relative_to(ROOT)}: {len(FP_SCHEMAS)} schemas")
